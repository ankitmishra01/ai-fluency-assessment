import json, sys, re

src = json.load(open(sys.argv[1]))
items, meta = src['items'], src['meta']

# Item removed in review: options C and D are both defensible explanations of the
# O(n^2) cost of self-attention, and D is truncated in the source document.
EXCLUDE = [('B', 'Why does self-attention scale quadratically with sequence length?')]

out = {}
for form in ('A', 'B'):
    rows = []
    n = 0
    for it in items[form]:
        if (form, it['q']) in EXCLUDE:
            continue
        n += 1
        rows.append({
            'id': f'{form}{n:02d}',
            'section': it['section'],
            'q': it['q'],
            'options': [{'key': k, 'text': it['options'][k]} for k in 'ABCD'],
            'answer': it['answer'],
        })
    out[form] = {
        'form': form,
        'scenario': {
            'title': meta[form]['scenario']['case'][0],
            'body': meta[form]['scenario']['case'][1],
        },
        'items': rows,
    }

ts = '// Generated by tools/parse_docx.py + emit.py from Ankit Mishra\'s source test documents.\n'
ts += '// Do not edit by hand; re-run the parser instead.\n\n'
ts += 'import type { Form } from "./types";\n\n'
ts += 'export const FORMS: Record<"A" | "B", Form> = ' + json.dumps(out, indent=2, ensure_ascii=False) + ' as const;\n'
open(sys.argv[2], 'w').write(ts)

from collections import Counter
for f in out:
    print(f, len(out[f]['items']), Counter(i['section'] for i in out[f]['items']))
